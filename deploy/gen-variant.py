#!/usr/bin/env python3
"""Generate an aggregated Qwen3-8B DGD variant from deploy/agg-qwen3-8b.yaml with extra vLLM flags / env.
Used for the H100 tuning matrix (chunking, batching, speculative decoding, fusion passes, FP8) so every variant
differs from the baseline ONLY in the flags listed here.

  python3 deploy/gen-variant.py <name> [--replicas N] [--env K=V ...] -- <extra vllm args...>
  e.g. python3 deploy/gen-variant.py agg-mbt8k -- --max-num-batched-tokens 8192
Writes deploy/variants/<name>.yaml (DGD name = <name>, services <name>-frontend / <name>-vllmdecodeworker).
"""
import argparse, pathlib, sys
import yaml

root = pathlib.Path(__file__).resolve().parent
ap = argparse.ArgumentParser()
ap.add_argument("name"); ap.add_argument("--replicas", type=int, default=1); ap.add_argument("--env", action="append", default=[])
argv = sys.argv[1:]
extra = argv[argv.index("--") + 1:] if "--" in argv else []
a = ap.parse_args(argv[:argv.index("--")] if "--" in argv else argv)

d = yaml.safe_load(open(root / "agg-qwen3-8b.yaml"))
d["metadata"]["name"] = a.name
w = next(c for c in d["spec"]["components"] if c["name"] == "VllmDecodeWorker")
w["replicas"] = a.replicas
ct = w["podTemplate"]["spec"]["containers"][0]
args = ct["args"]
for i in range(0, len(extra)):                       # an extra flag that already exists replaces its value
    f = extra[i]
    if f.startswith("--") and f in args and i + 1 < len(extra) and not extra[i + 1].startswith("--"):
        args[args.index(f) + 1] = extra[i + 1]
merged = [x for i, x in enumerate(extra)
          if not (x.startswith("--") and x in args and i + 1 < len(extra) and not extra[i + 1].startswith("--"))
          and not (i > 0 and extra[i - 1].startswith("--") and extra[i - 1] in args and not x.startswith("--"))]
ct["args"] = args + merged
for kv in a.env:
    k, v = kv.split("=", 1)
    ct.setdefault("env", []).append({"name": k, "value": v})
out = root / "variants" / f"{a.name}.yaml"
out.parent.mkdir(exist_ok=True)
hdr = f"# GENERATED by deploy/gen-variant.py from agg-qwen3-8b.yaml. Extra vLLM args: {' '.join(extra) or '(none)'}; env: {a.env}\n"
out.write_text(hdr + yaml.safe_dump(d, sort_keys=False, width=200))
print(out, "->", ct["args"])
